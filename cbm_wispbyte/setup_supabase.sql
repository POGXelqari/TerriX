-- Safe migration if cbm_pending_donations.id was created as UUID
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' 
          AND table_name = 'cbm_pending_donations' 
          AND column_name = 'id' 
          AND data_type = 'uuid'
    ) THEN
        ALTER TABLE public.cbm_pending_donations DROP CONSTRAINT IF EXISTS cbm_pending_donations_pkey CASCADE;
