DO $$
DECLARE
    tbl text;
    -- Public telemetry tables: Safe for anonymous and authenticated read access
    public_tables text[] := ARRAY[
        'cbm_vault_snapshots', 'cbm_sponsorship_slots', 'cbm_sponsored_ads', 
        'cbm_assets', 'cbm_products'
    ];
    -- Sensitive member & treasury tables: Access strictly restricted to backend service_role
    sensitive_tables text[] := ARRAY[
        'cbm_accounts', 'cbm_ledger', 'cbm_treasury', 'cbm_processed_txs',
        'cbm_withdrawals', 'cbm_loans', 'cbm_payment_methods', 'cbm_donations',
        'cbm_pending_donations', 'cbm_admin_votes', 'cbm_product_orders', 
        'cbm_referrals', 'cbm_ad_publishers', 'cbm_api_keys', 'cbm_chat_whitelist',
        'cbm_user_identities'
    ];
BEGIN
    -- 1. Configure Public Telemetry Tables (Read-only for public, managed by service_role)
    FOREACH tbl IN ARRAY public_tables LOOP
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', 'Allow public read ' || tbl, tbl);
        EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO anon, authenticated USING (TRUE)', 'Allow public read ' || tbl, tbl);
        
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', 'Service role manage ' || tbl, tbl);
        EXECUTE format('CREATE POLICY %I ON public.%I FOR ALL TO service_role USING (TRUE) WITH CHECK (TRUE)', 'Service role manage ' || tbl, tbl);
    END LOOP;

    -- 2. Lockdown Sensitive Tables (Revoke ALL public/anon read access; service_role ONLY)
    FOREACH tbl IN ARRAY sensitive_tables LOOP
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', 'Allow public read ' || tbl, tbl);
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', 'Public read ' || tbl, tbl);
        
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', 'Service role manage ' || tbl, tbl);
        EXECUTE format('CREATE POLICY %I ON public.%I FOR ALL TO service_role USING (TRUE) WITH CHECK (TRUE)', 'Service role manage ' || tbl, tbl);
    END LOOP;
END $$;

