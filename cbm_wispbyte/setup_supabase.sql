              'key_id', 'key_hash', 'claim_id', 'account_name', 'tx_id',
              'territorial_account_name', 'filename'
          )
    LOOP
        EXECUTE format('ALTER TABLE public.%I ALTER COLUMN %I DROP NOT NULL', rec.table_name, rec.column_name);
    END LOOP;

    -- Ensure all timestamp columns across all tables are normalized to TIMESTAMPTZ
    FOR rec IN 
        SELECT table_name, column_name 
        FROM information_schema.columns 
        WHERE table_schema = 'public' 
          AND table_name IN (
              'cbm_sponsorship_slots', 'cbm_sponsored_ads', 'cbm_products', 
