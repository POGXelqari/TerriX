-- Safe migration if cbm_loans.id was previously defined as UUID
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' 
          AND table_name = 'cbm_loans' 
          AND column_name = 'id' 
          AND data_type = 'uuid'
    ) THEN
        ALTER TABLE public.cbm_loans DROP CONSTRAINT IF EXISTS cbm_loans_pkey CASCADE;
        ALTER TABLE public.cbm_loans RENAME COLUMN id TO old_uuid_id;
        ALTER TABLE public.cbm_loans ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;
        ALTER TABLE public.cbm_loans DROP COLUMN old_uuid_id;
    END IF;
END $$;

ALTER TABLE public.cbm_loans ADD COLUMN IF NOT EXISTS penalty_interest_rate NUMERIC DEFAULT 50.0;
ALTER TABLE public.cbm_loans ADD COLUMN IF NOT EXISTS penalty_cents BIGINT DEFAULT 0;
ALTER TABLE public.cbm_loans ADD COLUMN IF NOT EXISTS borrower_territorial_account TEXT;
